def without_characters_forbidden_in_a_filename(string) :
    handled_characters = {"/":"", "|":"", "\\":"", ":":"", '"':"", "?":"", "*":"", "<":"", ">":""}
    for char in handled_characters.keys() :
        string = handled_characters[char].join(string.split(char))
    return string


def without_accents(string) :
    """
    This is some unicode magic that I copy/pasted from an answer to :
    https://stackoverflow.com/questions/517923/
    """
    nfkd_form = unicodedata.normalize('NFKD', string)
    return str(u"".join([c for c in nfkd_form if not unicodedata.combining(c)]))





def create_folder(path) :
    # type: (str) -> bool
    """
    Creates a folder, and all the parent folders in its arborescence.
    Does nothing if the target folder already exists.
    Works like os.makedirs, but without raising an error if the folder already
    exists.
    
    Parameters
    ----------
    path : string
        Path of the desired folder
    
    Returns
    -------
    callback : bool
        True if a new folder was created. False if it already existed.
    """
    try :
        os.makedirs(path)
        return True
    except FileExistsError :
        return False
