"""
The following function is a decorator function :
    a function intended to alter how other functions work.
Once you have defined a decorator like 'my_decorator', you can use
    the following syntax :

@my_decorator
def my_function(...) :
    (...)

This acts like :

def my_function(...) :
    (...)
my_function = my_decorator(my_function)
"""
def preserve_cwd(function) :
    # type: (Callable) -> Callable
    """
    Function decorator.
    Upon calling the decorated function, stores the initial value of the
    working directory ; sets the working directory to that value after the
    function call.
    """
    @wraps(function)
    def decorated_function(*args, **kwargs) :
        path = os.getcwd()
        returned_value = function(*args, **kwargs)
        os.chdir(path)
        return returned_value
    return decorated_function
preserve_cwd.__annotations__ = {'function':Callable, 'return':Callable}






















